import { glob, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const GENERATED_FILE = "dev/gallery/stories.generated.ts";
const PRESENTATIONAL_COMPONENT_PATTERNS = ["src/**/ui/**/*.tsx"];
const STORY_PATTERNS = ["src/**/*.stories.tsx"];

function isPresentationalComponent(filePath) {
  return !filePath.endsWith(".test.tsx") && !filePath.endsWith(".stories.tsx");
}

function toModuleId(filePath, suffix) {
  const sourcePath = path.relative("src", filePath).split(path.sep).join("/");
  return `@/${sourcePath.slice(0, -suffix.length)}`;
}

async function findFiles(projectRoot, patterns) {
  const files = new Set();

  for (const pattern of patterns) {
    for await (const filePath of glob(pattern, { cwd: projectRoot })) {
      files.add(filePath);
    }
  }

  return Array.from(files).sort((left, right) =>
    left.localeCompare(right, "en", { numeric: true })
  );
}

function renderGeneratedSource(storyFiles, presentationalComponentIds, orphanedStories) {
  const moduleEntries = storyFiles.map((storyFile) => {
    const storyId = toModuleId(storyFile, ".stories.tsx");
    const componentId = presentationalComponentIds.has(storyId) ? storyId : null;

    return [
      "  {",
      `    componentId: ${JSON.stringify(componentId)},`,
      `    load: (): Promise<unknown> => import(${JSON.stringify(`${storyId}.stories`)}),`,
      "  },",
    ].join("\n");
  });

  const orphanedComment =
    orphanedStories.length > 0
      ? `// ⚠ ${orphanedStories.length} orphaned stories found (no matching component):\n// ${orphanedStories.join(", ")}\n`
      : "";

  return [
    "// Generated by scripts/gen-gallery-stories.mjs. Do not edit.",
    orphanedComment,
    `export const presentationalComponentCount = ${presentationalComponentIds.size};`,
    "",
    "export const modules = [",
    ...moduleEntries,
    "] as const;",
    "",
  ].join("\n");
}

async function generateGalleryStories(projectRoot) {
  try {
    const [storyFiles, componentFiles] = await Promise.all([
      findFiles(projectRoot, STORY_PATTERNS),
      findFiles(projectRoot, PRESENTATIONAL_COMPONENT_PATTERNS),
    ]);

    const presentationalComponentIds = new Set(
      componentFiles
        .filter(isPresentationalComponent)
        .map((filePath) => toModuleId(filePath, ".tsx"))
    );

    // Track orphaned stories (no matching component)
    const orphanedStories = storyFiles
      .map((storyFile) => {
        const storyId = toModuleId(storyFile, ".stories.tsx");
        return presentationalComponentIds.has(storyId) ? null : storyId;
      })
      .filter((id) => id !== null);

    if (orphanedStories.length > 0) {
      console.warn(
        `⚠ Warning: ${orphanedStories.length} story(ies) have no matching component:\n  ${orphanedStories.join("\n  ")}`
      );
    }

    const outputPath = path.join(projectRoot, GENERATED_FILE);

    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, renderGeneratedSource(storyFiles, presentationalComponentIds, orphanedStories));

    console.log(`✓ Generated gallery stories (${storyFiles.length} stories, ${presentationalComponentIds.size} components)`);
    console.log(`  Output: ${outputPath}`);
  } catch (error) {
    console.error("✗ Failed to generate gallery stories:", error.message);
    process.exit(1);
  }
}

await generateGalleryStories(process.cwd());
